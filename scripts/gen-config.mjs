// Writes prototype/config.js from .env (or the process environment) so the web and Android apps point
// at a real Supabase project.   Usage: node scripts/gen-config.mjs [path/to/.env]
// Only public values go into config.js. A service_role key is refused.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envFile = process.argv[2] || path.join(root, '.env');
const env = { ...process.env };
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const fail = (msg) => { console.error('gen-config: ' + msg); process.exit(1); };
const url = (env.SUPABASE_URL || '').replace(/\/$/, '');
const key = env.SUPABASE_ANON_KEY || '';
if (!/^https?:\/\//.test(url)) fail('SUPABASE_URL is missing or not a URL.');
if (!key) fail('SUPABASE_ANON_KEY is missing.');
// legacy JWT keys carry their role; new-style keys are prefixed sb_publishable_ / sb_secret_
if (/^sb_secret_/.test(key)) fail('That is a secret key. Use the publishable (anon) key.');
try {
  const role = JSON.parse(Buffer.from(key.split('.')[1] || '', 'base64url').toString()).role;
  if (role && role !== 'anon') fail(`That key has role "${role}". Use the anon key; the service_role key must never reach the app.`);
} catch (e) { /* not a JWT: publishable key format */ }
const cfg = { source: 'env', supabaseUrl: url, supabaseAnonKey: key, appUrl: (env.APP_URL || '').replace(/\/$/, '') };
if (env.MAP_TILE_URL) cfg.mapTiles = { light: env.MAP_TILE_URL, attribution: env.MAP_TILE_ATTRIBUTION || '&copy; OpenStreetMap contributors' };
const out = path.join(root, 'prototype', 'config.js');
fs.writeFileSync(out, `// Generated by scripts/gen-config.mjs from .env. Public values only. Do not commit.\nwindow.DO_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
console.log('Wrote ' + path.relative(root, out) + ' → ' + url);
