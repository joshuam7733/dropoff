// Builds the self-contained app bundle used by the Android APKs (and testable in a browser):
//   prototype/_local/  =  the web app  +  the backend core  +  PGlite (Postgres in WebAssembly)
//                         +  a pre-built database (migrations + demo seed)  +  a "local" config.js
// Inside the app, supabase-js talks to core.mjs through an in-page fetch, so every rule, RLS policy and
// payment check is the same code as the server, but the data lives on the device (IndexedDB).
// Usage: tools\node\node.exe devserver\build-local.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import * as payCore from '../supabase/functions/_shared/payments/core.mjs';
import { sandboxPage } from '../supabase/functions/_shared/payments/sandbox-page.mjs';
import { bootstrap, createBackend } from './core.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const proto = path.join(root, 'prototype');
// default: prototype/_local (served by the dev server for browser testing); the APK build passes its own folder
const outDir = process.argv[2] ? path.resolve(process.argv[2]) : path.join(proto, '_local');
const ORIGIN = 'https://dropoff.local';            // the APK serves its assets on this origin
const API = ORIGIN + '/sb';                         // never hits the network: handled in-page
const SECRET = 'dropoff-on-device-demo-secret-0001'; // signs on-device sessions only; the data never leaves the phone
const version = 'v' + Date.now().toString(36);

const copy = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); };
const copyDir = (from, to, keep) => {
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) copyDir(a, b, keep);
    else if (!keep || keep(e.name)) copy(a, b);
  }
};
fs.rmSync(outDir, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 });

// 1 · database: migrations + demo seed, dumped so the phone starts in a second instead of replaying SQL
console.log('· building the on-device database');
const db = new PGlite({ extensions: { pgcrypto } });
const migDir = path.join(root, 'supabase', 'migrations');
await bootstrap(db, {
  shim: fs.readFileSync(path.join(here, 'shim.sql'), 'utf8'),
  migrations: fs.readdirSync(migDir).filter((x) => x.endsWith('.sql')).sort().map((name) => ({ name, sql: fs.readFileSync(path.join(migDir, name), 'utf8') })),
  seed: fs.readFileSync(path.join(root, 'supabase', 'seed.sql'), 'utf8'),
  appUrl: ORIGIN
});
const be = await createBackend({ db, apiUrl: API, appUrl: ORIGIN, secret: SECRET, payments: { ...payCore, sandboxPage } });
const dump = await db.dumpDataDir('gzip');
fs.mkdirSync(path.join(outDir, 'local'), { recursive: true });
fs.writeFileSync(path.join(outDir, 'local', 'dropoff-db.tar.gz'), Buffer.from(await dump.arrayBuffer()));
await db.close();

// 2 · runtime: PGlite (browser build), the backend core and the shared payment modules
const pg = path.join(here, 'node_modules', '@electric-sql', 'pglite', 'dist');
copyDir(pg, path.join(outDir, 'local', 'pglite'), (n) => /\.(js|wasm|data)$/.test(n) || n === 'pgcrypto.tar.gz');
copy(path.join(here, 'core.mjs'), path.join(outDir, 'local', 'core.mjs'));
for (const f of fs.readdirSync(path.join(root, 'supabase', 'functions', '_shared', 'payments'))) copy(path.join(root, 'supabase', 'functions', '_shared', 'payments', f), path.join(outDir, 'local', 'payments', f));
copy(path.join(proto, 'local', 'boot.js'), path.join(outDir, 'local', 'boot.js'));
copy(path.join(proto, 'local', 'backend.mjs'), path.join(outDir, 'local', 'backend.mjs'));

// 3 · the app itself, with a local config and the two loader scripts added to every page
for (const d of ['js', 'lib']) copyDir(path.join(proto, d), path.join(outDir, d));
for (const f of fs.readdirSync(proto).filter((n) => /\.(css|html|png|svg|ico|webmanifest)$/.test(n))) copy(path.join(proto, f), path.join(outDir, f));
const cfg = { source: 'local', local: true, supabaseUrl: API, supabaseAnonKey: be.anonKey, appUrl: ORIGIN, localSecret: SECRET, localDbVersion: version };
fs.writeFileSync(path.join(outDir, 'config.js'), `// On-device build (generated by devserver/build-local.mjs). Data stays on this device.\nwindow.DO_CONFIG = ${JSON.stringify(cfg)};\n`);
for (const f of fs.readdirSync(outDir).filter((n) => n.endsWith('.html'))) {
  const p = path.join(outDir, f);
  let s = fs.readFileSync(p, 'utf8');
  s = s.replace('<script src="config.js"></script>', '<script src="config.js"></script>\n<script src="local/boot.js"></script>\n<script type="module" src="local/backend.mjs"></script>');
  fs.writeFileSync(p, s);
}
const size = (d) => fs.readdirSync(d, { withFileTypes: true }).reduce((s, e) => s + (e.isDirectory() ? size(path.join(d, e.name)) : fs.statSync(path.join(d, e.name)).size), 0);
console.log(`· wrote ${path.relative(root, outDir)} (${(size(outDir) / 1048576).toFixed(1)} MB, database ${version})`);
